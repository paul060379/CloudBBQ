  const tables = {zh, en};
  const supported = Object.keys(tables);
  const DEFAULT = 'zh';
  const KEY = 'picnic-lang';

  function saved() { try { return localStorage.getItem(KEY); } catch { return null; } }
  function remember(value) { try { localStorage.setItem(KEY, value); } catch {} }
  /* Chinese unless this visitor switched away from it before. */
  function detect() { const stored = saved(); return supported.includes(stored) ? stored : DEFAULT; }

  let current = detect();

  function format(text, params) {
    if (!params) return text;
    return text.replace(/\{(\w+)\}/g, (match, name) => name in params ? String(params[name]) : match);
  }
  function t(key, params) {
    const text = tables[current]?.[key] ?? tables[DEFAULT][key] ?? key;
    return format(text, params);
  }
  /* Random line out of a numbered pool, e.g. pick('chatter.idle'); returns a key, so it re-translates. */
  function pool(prefix) { const table = tables[current] || tables[DEFAULT], head = prefix + '.'; return Object.keys(table).filter(key => key.startsWith(head)); }
  function pick(prefix, avoid) {
    const keys = pool(prefix);
    if (!keys.length) return null;
    const choices = keys.length > 1 && avoid ? keys.filter(key => key !== avoid) : keys;
    return choices[Math.floor(Math.random() * choices.length)];
  }
  function values(node) {
    const raw = node.dataset?.i18nParams;
    if (!raw) return undefined;
    try { return JSON.parse(raw); } catch { return undefined; }
  }
  function store(node, key, params) {
    if (!node.dataset) return;
    node.dataset.i18n = key;
    if (params) node.dataset.i18nParams = JSON.stringify(params); else delete node.dataset.i18nParams;
  }
  function set(node, key, params) { if (!node) return; store(node, key, params); node.textContent = t(key, params); }
  function apply(root) {
    const scope = root || (typeof document !== 'undefined' ? document : null);
    if (!scope || typeof scope.querySelectorAll !== 'function') return;
    scope.querySelectorAll('[data-i18n]').forEach(node => { node.textContent = t(node.dataset.i18n, values(node)); });
    scope.querySelectorAll('[data-i18n-html]').forEach(node => { node.innerHTML = t(node.dataset.i18nHtml, values(node)); });
    scope.querySelectorAll('[data-i18n-attr]').forEach(node => {
      for (const pair of node.dataset.i18nAttr.split(';')) {
        const [attribute, key] = pair.split(':').map(part => part && part.trim());
        if (attribute && key) node.setAttribute(attribute, t(key, values(node)));
      }
    });
    if (typeof document !== 'undefined' && document.documentElement) document.documentElement.lang = t('html.lang');
  }
  function setLanguage(value) {
    const next = supported.includes(value) ? value : current;
    if (next === current) return current;
    current = next; remember(next); apply();
    if (typeof window !== 'undefined' && typeof window.dispatchEvent === 'function') window.dispatchEvent(new Event('picnic-lang-change'));
    return current;
  }

  apply();
  return {t, set, pick, apply, language: () => current, setLanguage, toggle: () => setLanguage(current === 'zh' ? 'en' : 'zh'), languages: supported};
